#!/usr/bin/env python3
"""Build the two static pages from the checked-in chart and page templates.

Run from any working directory with Python 3:
    python scripts/build-site.py

The editable chart was exported from its approved inline visualization and
adapted to standalone HTML. Its embedded data and analytical logic are retained;
the two library URLs point to the vendored, versioned copies in assets/vendor.
No authoring-system runtime, network access, or package installation is required
to rebuild the pages. The normalized public data has a separate export script.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PLACEHOLDER = "<!-- INTERACTIVE_CHART -->"


def build() -> None:
    fragment_path = ROOT / "src" / "education-spending-and-income.html"
    fragment = fragment_path.read_text(encoding="utf-8")
    if re.search(r"<!doctype\s|<\s*(?:html|head|body)(?:\s|>)", fragment, re.I):
        raise ValueError("The source must be an HTML fragment.")
    if "window.openai" in fragment or "globalThis.openai" in fragment:
        raise ValueError("The chart must not depend on an authoring host API.")
    scripts = re.findall(r'<script\b[^>]*\bsrc="([^"]+)"', fragment)
    expected = [
        "assets/vendor/d3-7.9.0.min.js",
        "assets/vendor/topojson-client-3.1.0.min.js",
    ]
    if scripts != expected:
        raise ValueError("Unexpected chart script dependencies.")
    for relative in expected:
        if not (ROOT / relative).is_file():
            raise FileNotFoundError(relative)
    digest = hashlib.sha256(fragment.encode("utf-8")).hexdigest()
    provenance = f"<!-- Generated by scripts/build-site.py; chart SHA-256: {digest} -->\n"
    for page in ("index", "explore"):
        template = (ROOT / "assets" / f"{page}-template.html").read_text(encoding="utf-8")
        if template.count(PLACEHOLDER) != 1:
            raise ValueError(f"Expected one chart placeholder in {page} template.")
        document = template.replace(PLACEHOLDER, provenance + fragment.rstrip())
        output = ROOT / f"{page}.html"
        output.write_text(document, encoding="utf-8", newline="\n")
        print(f"Built {output.name}: {len(document.encode('utf-8')):,} bytes")


if __name__ == "__main__":
    build()
